/**
 * ============================================================================
 * HAPTIX PASSKEY ENGINE
 * ============================================================================
 *
 * TWO KEY MODES, ON PURPOSE
 * -------------------------
 * The module is dual-mode so that wallets already on Devnet keep working while
 * new wallets get a real platform credential.
 *
 *   HARDWARE (new wallets, native only)
 *     The keypair is generated by the platform authenticator through
 *     `react-native-passkey`, i.e. Android Credential Manager (whose keys live in
 *     the TEE/StrongBox-backed Keystore) or iOS ASAuthorization (Secure Enclave for
 *     platform credentials). The private key is non-exportable and never enters JS.
 *     Signing is a WebAuthn `navigator.credentials.get()`-equivalent ceremony that
 *     returns a signature, `authenticatorData` and `clientDataJSON`. Biometric
 *     verification is enforced by the authenticator itself (`userVerification:
 *     'required'`), and additionally gated by `expo-local-authentication` before the
 *     ceremony is invoked.
 *
 *   SOFTWARE (pre-existing wallets)
 *     A P-256 scalar generated from the platform CSPRNG, kept in `expo-secure-store`
 *     (iOS Keychain, Android Keystore-encrypted storage), gated behind an
 *     `expo-local-authentication` prompt, and materialised in JS memory to sign.
 *     This is NOT generated inside, or confined to, a secure element: a rooted or
 *     jailbroken device, or anything that can read the unlocked secure store, can
 *     extract the scalar. It is kept only so that existing on-chain wallets — whose
 *     PDA is derived from the public key — keep the same address.
 *
 * WHAT IS AND IS NOT CLAIMED
 * --------------------------
 * Hardware-mode keys are described as "platform passkey": the OS guarantees the
 * private key is generated in and used by the authenticator, and that it cannot be
 * exported. That is a real, enforceable property.
 *
 * We do NOT claim attestation or a specific secure element. The registration
 * requests `attestation: 'none'`, so nothing here cryptographically proves the key
 * lives in a TPM/Secure Enclave/StrongBox rather than a software authenticator
 * that the user installed. No string in this app may claim more than that.
 *
 * ON-CHAIN VERIFICATION
 * ---------------------
 * Both modes are verified by Solana's native Secp256r1SigVerify precompile, with two
 * wire formats:
 *
 *   legacy  - the message region is the raw payload; the program binds it byte-for-byte.
 *   webauthn- the message region is `authenticatorData || sha256(clientDataJSON)`;
 *             the digest is identical to what the authenticator signed, and
 *             `programs/haptix_program/src/webauthn.rs` validates the assertion's
 *             structure and requires its `challenge` to decode to the payload.
 *
 * Web builds have no native authenticator plugin here; they use the browser's
 * WebAuthn implementation, which also never exposes key material to JS.
 */

