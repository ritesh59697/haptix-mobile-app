const BASE64URL_ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_'

const BASE64URL_LOOKUP: Int16Array = (() => {
  const table = new Int16Array(128).fill(-1)
  for (let i = 0; i < BASE64URL_ALPHABET.length; i++) {
    table[BASE64URL_ALPHABET.charCodeAt(i)] = i
  }
  // Tolerate standard base64 padding in values produced elsewhere.
  table['='.charCodeAt(0)] = -2
  return table
})()

/**
 * Unpadded base64url, implemented locally rather than via `btoa`/`atob` so the
 * hardware path behaves identically on Hermes, on JSC and on web.
 */
function bytesToBase64Url(bytes: Uint8Array): string {
  let out = ''
  for (let i = 0; i < bytes.length; i += 3) {
    const b0 = bytes[i]
    const b1 = i + 1 < bytes.length ? bytes[i + 1] : 0
    const b2 = i + 2 < bytes.length ? bytes[i + 2] : 0
    const triple = (b0 << 16) | (b1 << 8) | b2

    out += BASE64URL_ALPHABET[(triple >> 18) & 0x3f]
    out += BASE64URL_ALPHABET[(triple >> 12) & 0x3f]
    if (i + 1 < bytes.length) out += BASE64URL_ALPHABET[(triple >> 6) & 0x3f]
    if (i + 2 < bytes.length) out += BASE64URL_ALPHABET[triple & 0x3f]
  }
  return out
}

function base64UrlToBytes(base64url: string): Uint8Array {
  const out = new Uint8Array(Math.floor((base64url.length * 3) / 4))
  let outIndex = 0
  let buffer = 0
  let bits = 0

  for (let i = 0; i < base64url.length; i++) {
    const code = base64url.charCodeAt(i)
    const value = code < 128 ? BASE64URL_LOOKUP[code] : -1
    if (value === -2) break // padding: nothing meaningful follows
    if (value < 0) {
      throw new Error('Invalid base64url character in WebAuthn payload.')
    }
    buffer = (buffer << 6) | value
    bits += 6
    if (bits >= 8) {
      bits -= 8
      out[outIndex++] = (buffer >> bits) & 0xff
    }
  }

  return out.subarray(0, outIndex)
}

/** Extracts the 33-byte compressed point from a SPKI DER public key. */
function extractCompressedP256FromSpki(spkiBytes: Uint8Array): Uint8Array {
  if (spkiBytes.length < 65) {
    throw new Error('SPKI buffer is too short')
  }
  const uncompressed = spkiBytes.slice(spkiBytes.length - 65)
  if (uncompressed[0] !== 0x04) {
    throw new Error('Invalid EC uncompressed point prefix')
  }
  const point = p256.Point.fromHex(bytesToHex(uncompressed))
  return point.toRawBytes(true)
}

