type CborValue = number | string | Uint8Array | boolean | null | CborValue[] | Map<CborValue, CborValue>

/**
 * Minimal CBOR reader, sized for the WebAuthn attestation object.
 *
 * `attestationObject` is a CBOR map of `{ fmt, attStmt, authData }`, and `authData`
 * in turn embeds a COSE_Key map. A full CBOR implementation would be a lot of
 * untrusted-input handling for two small, fixed shapes, so this handles exactly the
 * major types those structures use and rejects everything else (indefinite lengths,
 * floats, tags with content we would have to interpret).
 */
class CborReader {
  private offset = 0

  constructor(private readonly bytes: Uint8Array) {}

  readValue(): CborValue {
    const initial = this.take(1)[0]
    const major = initial >> 5
    const additional = initial & 0x1f

    switch (major) {
      case 0:
        return this.readLength(additional)
      case 1:
        return -1 - this.readLength(additional)
      case 2:
        return this.take(this.readLength(additional))
      case 3:
        return decodeUtf8(this.take(this.readLength(additional)))
      case 4: {
        const length = this.readLength(additional)
        const items: CborValue[] = []
        for (let i = 0; i < length; i++) items.push(this.readValue())
        return items
      }
      case 5: {
        const length = this.readLength(additional)
        const map = new Map<CborValue, CborValue>()
        for (let i = 0; i < length; i++) {
          const key = this.readValue()
          map.set(key, this.readValue())
        }
        return map
      }
      case 6:
        // Tag: we never need the tag itself, only the tagged value.
        this.readLength(additional)
        return this.readValue()
      case 7:
        switch (additional) {
          case 20:
            return false
          case 21:
            return true
          case 22:
            return null
          case 24:
            this.take(1)
            return null
          case 25:
            this.take(2)
            return null
          case 26:
            this.take(4)
            return null
          case 27:
            this.take(8)
            return null
          default:
            throw new Error(`Unsupported CBOR simple value ${additional}.`)
        }
      default:
        throw new Error(`Unsupported CBOR major type ${major}.`)
    }
  }

  private readLength(additional: number): number {
    if (additional < 24) return additional
    if (additional === 24) return this.take(1)[0]
    if (additional === 25) {
      const high = this.take(1)[0]
      const low = this.take(1)[0]
      return (high << 8) | low
    }
    if (additional === 26) {
      const b = this.take(4)
      return ((b[0] << 24) | (b[1] << 16) | (b[2] << 8) | b[3]) >>> 0
    }
    throw new Error('Unsupported CBOR length encoding (indefinite lengths are not valid here).')
  }

  private take(length: number): Uint8Array {
    const end = this.offset + length
    if (length < 0 || end > this.bytes.length) {
      throw new Error('Truncated CBOR structure in the WebAuthn attestation object.')
    }
    const slice = this.bytes.subarray(this.offset, end)
    this.offset = end
    return slice
  }
}

/** UTF-8 decode without a TextDecoder global, which Hermes does not guarantee. */
function decodeUtf8(bytes: Uint8Array): string {
  let out = ''
  let i = 0
  while (i < bytes.length) {
    const byte = bytes[i]
    let codePoint: number

    if (byte < 0x80) {
      codePoint = byte
      i += 1
    } else if ((byte & 0xe0) === 0xc0 && i + 1 < bytes.length) {
      codePoint = ((byte & 0x1f) << 6) | (bytes[i + 1] & 0x3f)
      i += 2
    } else if ((byte & 0xf0) === 0xe0 && i + 2 < bytes.length) {
      codePoint = ((byte & 0x0f) << 12) | ((bytes[i + 1] & 0x3f) << 6) | (bytes[i + 2] & 0x3f)
      i += 3
    } else if ((byte & 0xf8) === 0xf0 && i + 3 < bytes.length) {
      codePoint =
        ((byte & 0x07) << 18) | ((bytes[i + 1] & 0x3f) << 12) | ((bytes[i + 2] & 0x3f) << 6) | (bytes[i + 3] & 0x3f)
      i += 4
    } else {
      codePoint = 0xfffd
      i += 1
    }

    if (codePoint > 0xffff) {
      const adjusted = codePoint - 0x10000
      out += String.fromCharCode(0xd800 + (adjusted >> 10), 0xdc00 + (adjusted & 0x3ff))
    } else {
      out += String.fromCharCode(codePoint)
    }
  }
  return out
}

const AUTH_DATA_MIN_LEN = 37
/** `authenticatorData` flags: attested credential data and extensions. */
const AUTH_DATA_FLAG_ATTESTED_CREDENTIAL_DATA = 0x40

/** COSE_Key labels for an EC2 key. */
const COSE_KEY_KTY = 1
const COSE_KEY_CRV = -1
const COSE_KEY_X = -2
const COSE_KEY_Y = -3
const COSE_KTY_EC2 = 2
const COSE_CRV_P256 = 1

/**
 * Pulls the 33-byte compressed public key out of `authenticatorData`.
 *
 * Only possible when the authenticator set the attested-credential-data flag, which
 * is why registration asks for a resident (discoverable) credential.
 */
function extractCompressedP256FromAuthData(authData: Uint8Array): Uint8Array {
  if (authData.length < AUTH_DATA_MIN_LEN) {
    throw new Error('The authenticator returned a truncated attestation.')
  }
  if ((authData[32] & AUTH_DATA_FLAG_ATTESTED_CREDENTIAL_DATA) === 0) {
    throw new Error(
      'The authenticator did not attest a credential public key, so the wallet address ' +
        'cannot be derived from this registration.',
    )
  }

  let offset = AUTH_DATA_MIN_LEN + 16 // skip rpIdHash, flags, signCount and aaguid
  if (offset + 2 > authData.length) {
    throw new Error('The authenticator returned a truncated attestation.')
  }
  const credentialIdLength = (authData[offset] << 8) | authData[offset + 1]
  offset += 2 + credentialIdLength
  if (offset >= authData.length) {
    throw new Error('The authenticator returned a truncated attestation.')
  }

  const cose = new CborReader(authData.subarray(offset)).readValue()
  if (!(cose instanceof Map)) {
    throw new Error('The attested credential public key is not a COSE key.')
  }

  const kty = cose.get(COSE_KEY_KTY)
  const crv = cose.get(COSE_KEY_CRV)
  const x = cose.get(COSE_KEY_X)
  const y = cose.get(COSE_KEY_Y)

  if (kty !== COSE_KTY_EC2 || crv !== COSE_CRV_P256) {
    throw new Error('The authenticator produced an unsupported key type; Haptix needs ES256 (P-256).')
  }
  if (!(x instanceof Uint8Array) || x.length !== 32 || !(y instanceof Uint8Array) || y.length !== 32) {
    throw new Error('The attested credential public key has an unexpected coordinate length.')
  }

  const uncompressed = new Uint8Array(65)
  uncompressed[0] = 0x04
  uncompressed.set(x, 1)
  uncompressed.set(y, 33)

  try {
    return p256.Point.fromHex(bytesToHex(uncompressed)).toRawBytes(true)
  } catch {
    throw new Error('The attested credential public key is not a valid P-256 point.')
  }
}

/** `attestationObject` (CBOR) → attested credential public key. */
function extractCompressedP256FromAttestationObject(attestationObject: Uint8Array): Uint8Array {
  const decoded = new CborReader(attestationObject).readValue()
  if (!(decoded instanceof Map)) {
    throw new Error('The authenticator returned a malformed attestation object.')
  }
  const authData = decoded.get('authData')
  if (!(authData instanceof Uint8Array)) {
    throw new Error('The authenticator returned a malformed attestation object.')
  }
  return extractCompressedP256FromAuthData(authData)
}

/**
 * Recovers the registration public key.
 *
 * Android Credential Manager returns the SPKI-encoded key directly; iOS returns only
 * the CBOR attestation object, so the COSE key has to be decoded out of it.
 */
function extractPublicKeyFromRegistration(response: { publicKey?: string; attestationObject?: string }): Uint8Array {
  if (response.publicKey) {
    return extractCompressedP256FromSpki(base64UrlToBytes(response.publicKey))
  }
  if (response.attestationObject) {
    return extractCompressedP256FromAttestationObject(base64UrlToBytes(response.attestationObject))
  }
  throw new Error(
    'The authenticator returned neither a public key nor an attestation object, so the ' +
      'wallet address cannot be derived from this passkey.',
  )
}

/**
 * Registers a platform passkey via WebAuthn. No key material reaches JS; the
 * authenticator holds the private key and we persist only the credential id and
 * public key.
 */
export async function registerWebAuthnPasskey(
  id: 'primary' | 'secondary' = 'primary',
  walletName: string = 'Haptix Wallet',
  attachment: 'platform' | 'cross-platform' = 'platform',
): Promise<PasskeyInfo> {
  if (Platform.OS !== 'web' || typeof window === 'undefined' || !window.PublicKeyCredential) {
    throw new Error('WebAuthn passkeys are not supported in this environment.')
  }

  const challenge = crypto.getRandomValues(new Uint8Array(32))
  const userId = crypto.getRandomValues(new Uint8Array(16))

  try {
    const credential = (await navigator.credentials.create({
      publicKey: {
        challenge,
        rp: { name: 'Haptix Wallet', id: window.location.hostname || 'localhost' },
        user: {
          id: userId,
          name: walletName,
          displayName: walletName,
        },
        pubKeyCredParams: [{ type: 'public-key', alg: -7 }], // ES256 / P-256
        authenticatorSelection: {
          authenticatorAttachment: attachment,
          userVerification: 'required',
          residentKey: 'preferred',
        },
        timeout: 60000,
        attestation: 'none',
      },
    })) as PublicKeyCredential | null

    if (!credential) {
      throw new Error('Passkey creation was cancelled.')
    }

    const rawId = new Uint8Array(credential.rawId)
    const credentialId = bytesToBase64Url(rawId)
    const response = credential.response as AuthenticatorAttestationResponse

    let compressedPublicKey: Uint8Array
    try {
      const spki = response.getPublicKey?.()
      if (!spki) throw new Error('Authenticator did not expose a public key')
      compressedPublicKey = extractCompressedP256FromSpki(new Uint8Array(spki))
    } catch {
      throw new Error(
        'This browser will not export the passkey public key, so the wallet address cannot be derived. Try Chrome or Safari.',
      )
    }

    const publicKeyHex = bytesToHex(compressedPublicKey)
    await AsyncStorage.setItem(credentialKey(id), credentialId)
    await AsyncStorage.setItem(pubkeyKey(id), publicKeyHex)

    return {
      id,
      credentialId,
      publicKey: compressedPublicKey,
      publicKeyHex,
      label: WEBAUTHN_LABEL,
      hasBiometrics: true,
      mode: 'hardware',
      hardwareBacked: true,
    }
  } catch (err: any) {
    console.error(`[Haptix Passkey] WebAuthn registration failed for ${id}:`, err)
    if (err?.name === 'NotAllowedError') {
      throw new Error('Passkey creation was cancelled. Complete the platform verification to continue.')
    }
    throw new Error(err?.message || 'Failed to create a passkey.')
  }
}

